// Periodic face reinforcement: intersections of the two level sets with x/y/z=0.
// The generated perimeter members are a design addition, not reported Fig. 4 bonds.
import {mod1,add,sub,norm,mimgDist} from './geom.mjs';
import {F} from './gyroid.mjs';
import {addBoundaryBraces} from './boundary-braces.mjs';

export function reinforceBoundary(model, resolution=48) {
 const {vertices,edges,w}=model;
 const original=edges.splice(0); const junctions=[];
 const index=new Map();
 function point(p,layer,role){
  const q=p.map(x=>{let a=mod1(x);return a>1-1e-9||a<1e-9?0:a});
  const k=layer+':'+q.map(x=>Math.round(x*1e8)).join(':');
  if(index.has(k)) return index.get(k);
  const i=vertices.length;vertices.push({p:q,layer,role});index.set(k,i);return i;
 }
 function emit(a,b,pa,pb,kind,role){
  if(a===b && norm(sub(pa,pb))<1e-8)return;
  const va=vertices[a].p,vb=vertices[b].p;
  const o=pa.map((x,k)=>Math.round(pb[k]-vb[k])-Math.round(x-va[k]));
  edges.push({a,b,o,kind,role,d:norm(sub(pb,pa))});
 }
 // Split the original periodic rods at the cell faces. The split point is a real
 // graph joint; the two halves still join across the periodic seam by offset.
 for(const e of original){
  if(e.kind==='cross'){edges.push({...e,role:'original'});continue;}
  const a=vertices[e.a].p,b=add(vertices[e.b].p,e.o),ts=[];
  for(let k=0;k<3;k++)if(Math.abs(b[k]-a[k])>1e-12){
   for(const plane of [0,1]){const t=(plane-a[k])/(b[k]-a[k]);if(t>1e-9&&t<1-1e-9)ts.push({t,axis:k});}
  }
  ts.sort((x,y)=>x.t-y.t);
  let prev=e.a,prevP=a;
  for(const item of ts){const p=a.map((v,k)=>v+(b[k]-v)*item.t), layer=vertices[e.a].layer;
   // White members only need splitting, not an added same-layer perimeter tie.
   const id=point(p,layer,e.kind==='cross'?'cross-seam':'seam');
   emit(prev,id,prevP,p,e.kind,'original');prev=id;prevP=p;
   if(e.kind!=='cross')junctions.push({id,axis:item.axis,layer});
  }
  emit(prev,e.b,prevP,b,e.kind,'original');
 }
 const railNodes=Array.from({length:2},()=>Array.from({length:3},()=>new Set()));
 const edgeKeys=new Set();
 function rail(a,b,pa,pb,layer,axis){
  if(a===b)return;const va=vertices[a].p,vb=vertices[b].p;
  const off=pa.map((v,k)=>Math.round(pb[k]-vb[k])-Math.round(v-va[k]));
  const s1=`${a},${b},${off}`,s2=`${b},${a},${off.map(x=>-x)}`,key=s1<s2?s1:s2;
  if(edgeKeys.has(key))return;edgeKeys.add(key);emit(a,b,pa,pb,layer?'blue':'red','boundary');
  railNodes[layer][axis].add(a);railNodes[layer][axis].add(b);
 }
 // Marching squares of g=+w and g=-w on the three unique periodic faces.
 // Face x=1 is generated by translating x=0, so both sides match exactly.
 for(let layer=0;layer<2;layer++)for(let axis=0;axis<3;axis++){
  const uv=[0,1,2].filter(x=>x!==axis),level=layer?-w:w;
  const at=(u,v)=>{const p=[0,0,0];p[uv[0]]=u;p[uv[1]]=v;return p};
  for(let i=0;i<resolution;i++)for(let j=0;j<resolution;j++){
   const p=[at(i/resolution,j/resolution),at((i+1)/resolution,j/resolution),at((i+1)/resolution,(j+1)/resolution),at(i/resolution,(j+1)/resolution)];
   const vals=p.map(x=>F(x)-level), hits=[];
   for(const [a,b] of [[0,1],[1,2],[2,3],[3,0]])if((vals[a]<0)!==(vals[b]<0)){
    const t=vals[a]/(vals[a]-vals[b]);hits.push(p[a].map((v,k)=>v+t*(p[b][k]-v)));
   }
   if(hits.length===2){const a=point(hits[0],layer,'boundary'),b=point(hits[1],layer,'boundary');rail(a,b,hits[0],hits[1],layer,axis)}
   else if(hits.length===4){ // asymptotic decider for the rare saddle square
    const center=F(at((i+.5)/resolution,(j+.5)/resolution))-level;
    const pairs=(center<0)===(vals[0]<0)?[[0,1],[2,3]]:[[0,3],[1,2]];
    for(const [u,v] of pairs){const a=point(hits[u],layer,'boundary'),b=point(hits[v],layer,'boundary');rail(a,b,hits[u],hits[v],layer,axis)}
   }
  }
 }
 // Tie each seam joint to the nearest contour vertex, i.e. the boundary frame
 // is connected to the original spatial network, not just decorative geometry.
 let maxTie=0;
 for(const j of junctions){let best=-1,dist=Infinity;const p=vertices[j.id].p;
  for(const id of railNodes[j.layer][j.axis]){const d=mimgDist(p,vertices[id].p);if(d<dist){dist=d;best=id}}
  if(best<0)continue;
  const q=vertices[best].p, image=q.map((v,k)=>v+Math.round(p[k]-v));
  if(j.id!==best)emit(j.id,best,p,image,j.layer?'blue':'red','tie');
  maxTie=Math.max(maxTie,dist);
 }
 const webs=addBoundaryBraces(model,junctions);
 return {junctionCount:junctions.length,maxTie,railCount:edgeKeys.size,resolution,webs};
}
